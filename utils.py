class PaginatorView(discord.ui.View):
    def __init__(self, author_id: int, title: str, entries: list, per_page: int = 10, color: int = config.DEFAULT_EMBED_COLOR, author_user: discord.Member = None, join_str: str = "\n", empty_text: str = "none", item_name: str = "items"):
        super().__init__(timeout=120)
        self.author_id = author_id
        self.title = title
        self.entries = entries
        self.per_page = per_page
        self.color = color
        self.author_user = author_user
        self.join_str = join_str
        self.empty_text = empty_text
        self.item_name = item_name
        self.current_page = 0
        self.total_pages = max(1, (len(entries) + per_page - 1) // per_page)
        self.message = None
        self.update_buttons()

    def update_buttons(self):
        self.prev_button.disabled = self.current_page == 0
        self.next_button.disabled = self.current_page >= self.total_pages - 1

    def get_embed(self) -> discord.Embed:
        start = self.current_page * self.per_page
        page_entries = self.entries[start:start + self.per_page]
        
        if not page_entries:
            desc = self.empty_text
        else:
            desc = self.join_str.join(page_entries)

        embed = discord.Embed(
            title=self.title,
            description=_truncate(_lower_preserving_urls(desc), 4096),
            color=self.color
        )
        if self.author_user and hasattr(self.author_user, "display_avatar"):
            embed.set_author(name=self.author_user.display_name.lower(), icon_url=self.author_user.display_avatar.url)
        embed.set_footer(text=f"page {self.current_page + 1}/{self.total_pages} • {len(self.entries):,} {self.item_name}")
        return embed

    async def interaction_check(self, interaction: discord.Interaction) -> bool:
        if interaction.user.id != self.author_id:
            await interaction.response.send_message("this menu is not for you", ephemeral=True)
            return False
        return True

    @discord.ui.button(label="◀", style=discord.ButtonStyle.primary)
    async def prev_button(self, interaction: discord.Interaction, button: discord.ui.Button):
        if self.current_page > 0:
            self.current_page -= 1
            self.update_buttons()
            await interaction.response.edit_message(embed=self.get_embed(), view=self)

    @discord.ui.button(label="▶", style=discord.ButtonStyle.primary)
    async def next_button(self, interaction: discord.Interaction, button: discord.ui.Button):
        if self.current_page < self.total_pages - 1:
            self.current_page += 1
            self.update_buttons()
            await interaction.response.edit_message(embed=self.get_embed(), view=self)

    @discord.ui.button(label="⇅", style=discord.ButtonStyle.secondary)
    async def jump_button(self, interaction: discord.Interaction, button: discord.ui.Button):
        self.current_page = 0
        self.update_buttons()
        await interaction.response.edit_message(embed=self.get_embed(), view=self)

    @discord.ui.button(label="✖", style=discord.ButtonStyle.danger)
    async def close_button(self, interaction: discord.Interaction, button: discord.ui.Button):
        await interaction.message.delete()

    async def on_timeout(self):
        for item in self.children:
            item.disabled = True
        if self.message:
            try:
                await self.message.edit(view=self)
            except Exception:
                pass


async def send_paginated_embed(ctx, title: str, entries: list, per_page: int = 10, color: int = config.DEFAULT_EMBED_COLOR, join_str: str = "\n", empty_text: str = "none", item_name: str = "items"):
    view = PaginatorView(
        author_id=ctx.author.id,
        title=title,
        entries=entries,
        per_page=per_page,
        color=color,
        author_user=ctx.author,
        join_str=join_str,
        empty_text=empty_text,
        item_name=item_name
    )
    embed = view.get_embed()
    if view.total_pages > 1:
        view.message = await ctx.send(embed=embed, view=view)
        return view.message
    else:
        return await ctx.send(embed=embed)



