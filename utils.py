async def send_modlog(bot, guild: discord.Guild, action: str, moderator: discord.Member, target = None, reason: str = "No reason provided") -> int:
    if not guild:
        return 0

    now_ts = int(time.time())
    user_id = target.id if target and hasattr(target, "id") else None
    mod_id = moderator.id if moderator and hasattr(moderator, "id") else 0
    clean_reason = reason if reason and str(reason).strip() else "No reason provided"

    # 1. Log to database
    try:
        await bot.db.execute(
            "INSERT INTO modhistory (guild_id, user_id, moderator_id, action, reason, timestamp) VALUES (?, ?, ?, ?, ?, ?)",
            (guild.id, user_id, mod_id, str(action).lower(), clean_reason, now_ts)
        )
    except Exception:
        pass

    # 2. Get case count for this guild
    case_num = 1
    try:
        row = await bot.db.fetchrow("SELECT COUNT(*) as count FROM modhistory WHERE guild_id = ?", (guild.id,))
        if row and row["count"]:
            case_num = row["count"]
    except Exception:
        pass

    # 3. Check guild modlog channel
    try:
        cfg = await bot.db.fetchrow("SELECT modlog_id FROM guild_settings WHERE guild_id = ?", (guild.id,))
        if cfg and cfg["modlog_id"]:
            channel = guild.get_channel(cfg["modlog_id"])
            if channel:
                # Format user string
                if target:
                    target_name = getattr(target, "name", getattr(target, "display_name", str(target)))
                    target_id = getattr(target, "id", "N/A")
                    user_str = f"{target_name} ( `{target_id}` )"
                else:
                    user_str = "N/A"

                # Format moderator string
                if moderator:
                    mod_name = getattr(moderator, "name", getattr(moderator, "display_name", str(moderator)))
                    mod_id_val = getattr(moderator, "id", "N/A")
                    mod_str = f"{mod_name} ( `{mod_id_val}` )"
                else:
                    mod_str = "N/A"

                # Action color
                act_lower = str(action).lower()
                if act_lower in ["ban", "hardban", "softban", "kick", "jail", "imute", "rmute", "mute", "timeout", "strip"]:
                    color = 0xED4245
                elif act_lower in ["unban", "unjail", "iunmute", "runmute", "unmute", "untimeout"]:
                    color = 0x57F287
                else:
                    color = 0x5865F2

                description = (
                    f"**Information**\n"
                    f"**Case #{case_num}** | {act_lower}\n"
                    f"**User:** {user_str}\n"
                    f"**Moderator:** {mod_str}\n"
                    f"**Reason:** {clean_reason}\n"
                    f"**Time:** <t:{now_ts}:R>"
                )

                embed = discord.Embed(
                    description=description,
                    color=color,
                    timestamp=datetime.datetime.now(datetime.timezone.utc)
                )
                icon_url = moderator.display_avatar.url if moderator and hasattr(moderator, "display_avatar") else (guild.icon.url if guild.icon else None)
                embed.set_author(name="Modlog Entry", icon_url=icon_url)

                await channel.send(embed=embed)
    except Exception:
        pass

    return case_num

async def send_group_help(ctx, group_cmd, module_name: str = None):
    mod_name = module_name or (group_cmd.cog_name.lower() if group_cmd.cog_name else "general")
