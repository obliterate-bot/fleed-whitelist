def find_role(guild: discord.Guild, query: str):
    if not guild or not query:
        return None
    query = str(query).strip()
    clean_id = re.sub(r'[<@&!>]', '', query)
    if clean_id.isdigit():
        role = guild.get_role(int(clean_id))
        if role:
            return role
    
    clean_query = query.lstrip("@").strip()
    if not clean_query:
        return None

    # 1. Exact match (case-sensitive)
    role = discord.utils.get(guild.roles, name=clean_query)
    if role:
        return role

    clean_lower = clean_query.lower()

    # 2. Exact match (case-insensitive)
    role = discord.utils.find(lambda r: r.name.lower() == clean_lower, guild.roles)
    if role:
        return role

    # 3. Starts with match (case-insensitive)
    role = discord.utils.find(lambda r: r.name.lower().startswith(clean_lower), guild.roles)
    if role:
        return role

    # 4. Substring / contains match (case-insensitive)
    role = discord.utils.find(lambda r: clean_lower in r.name.lower(), guild.roles)
    if role:
        return role

    return None

_orig_role_convert = commands.RoleConverter.convert

async def _flexible_role_convert(self, ctx, argument: str) -> discord.Role:
    guild = ctx.guild
    if not guild:
        raise commands.NoPrivateMessage()
    role = find_role(guild, argument)
    if role is not None:
        return role
    return await _orig_role_convert(self, ctx, argument)

_PRESERVE_RE = re.compile(r"```[\s\S]*?```|`[^`]+`|https?://[^\s<>]+|<a?:[a-zA-Z0-9_]+:[0-9]+>|<@[!&]?[0-9]+>|<#[0-9]+>|<t:[0-9]+(?::[tTdDfFR])?>|FLEED-[A-F0-9-]+|fg_live_[a-f0-9]+", re.IGNORECASE)



def _truncate(value, limit: int):
    """Return text that always fits the relevant Discord embed limit."""
    if value is None:
        return None
    text = str(value)
    if len(text) <= limit:
        return text
    return text[: max(0, limit - 1)] + "…"


def _lower_preserving_urls(value):
    """Keep the bot's lowercase style without corrupting case-sensitive URLs, custom emojis, or mentions."""
    if value is None:
        return None
    text = str(value)
    pieces = []
    cursor = 0
    for match in _PRESERVE_RE.finditer(text):
        pieces.append(text[cursor:match.start()].lower())
        pieces.append(match.group(0))
        cursor = match.end()
    pieces.append(text[cursor:].lower())
    return "".join(pieces)

def fleed_embed(title: str = None, description: str = None, color: int = config.DEFAULT_EMBED_COLOR, author: discord.Member = None, footer: str = None, image: str = None, thumbnail: str = None) -> discord.Embed:
    # all lowercase, no grammar, clean minimal embed styling
    title_str = _truncate(_lower_preserving_urls(title), 256) if title else None
    desc_str = _truncate(_lower_preserving_urls(description), 4096) if description else ""
    
    if author and not title_str:
        desc_str = f"{author.mention}: {desc_str}".strip()

    embed = discord.Embed(
        title=title_str,
        description=desc_str if desc_str else None,
        color=color
    )
    if image:
        embed.set_image(url=image)
    if thumbnail:
        embed.set_thumbnail(url=thumbnail)
    if footer:
        embed.set_footer(text=_truncate(_lower_preserving_urls(footer), 2048))
    return embed

